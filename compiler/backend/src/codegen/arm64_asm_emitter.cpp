Arm64AsmEmitter::Arm64AsmEmitter(const StringInterner& interner, AsmEmitterOptions options)
    : interner_(interner), options_(options) {}

std::string Arm64AsmEmitter::format_symbol(std::string_view raw_name) const {
    if (options_.target_os == TargetOs::MacOS) {
        std::string s;
        s.reserve(raw_name.size() + 1);
        s.push_back('_');
        s.append(raw_name);
        return s;
    }
    return std::string(raw_name);
}

std::string Arm64AsmEmitter::format_local_label(ir::LabelId label) const {
    return std::format(".L_{}_{}", current_func_name_, label);
}

void Arm64AsmEmitter::emit_line(std::string& out, std::string_view line) {
    out.append("    ");
    out.append(line);
    out.push_back('\n');
}

void Arm64AsmEmitter::emit_label(std::string& out, std::string_view label) {
    out.append(label);
    out.push_back('\n');
}

std::string Arm64AsmEmitter::emit_module(const ir::IrModule& module) {
    std::string out;
    out.append("// Generated by Axiom Compiler (AOT ARM64)\n");
    emit_line(out, ".text");
    out.push_back('\n');

    for (const auto& func : module.functions) {
        out.append(emit_function(func));
        out.push_back('\n');
    }

    return out;
}

std::string Arm64AsmEmitter::emit_function(const ir::IrFunction& func) {
    std::string out;
    current_func_name_ = interner_.GetString(func.name_id);
    std::string symbol = format_symbol(current_func_name_);

    // 1. レジスタ割り当て解析 (P6 LinearScanAllocator をそのまま再利用)
    jit::LivenessResult liveness = jit::compute_liveness(func);
    alloc_                       = jit::allocate_registers(func, liveness);

    // 2. スタックフレームサイズ計算 (16バイト境界アライメント)
    size_t raw_bytes = static_cast<size_t>(alloc_.num_spill_slots) * 4;
    frame_size_      = static_cast<uint16_t>((raw_bytes + 15) & ~size_t(15));

    // 3. シンボルおよびアライメントディレクティブ
    emit_line(out, ".p2align 2");
    emit_line(out, std::format(".globl {}", symbol));
    if (options_.target_os == TargetOs::Linux) {
        emit_line(out, std::format(".type {}, %function", symbol));
    }

    // 4. 関数エントリラベル
    emit_label(out, std::format("{}:", symbol));

    // 5. 関数プロローグ
    emit_prologue(func, out);

    // 6. 各 IR 命令の出力
    for (size_t i = 0; i < func.instructions.size(); ++i) {
        emit_instruction(func, func.instructions[i], i, out);
    }

    // 7. Linux ELF 用のサイズディレクティブ
    if (options_.target_os == TargetOs::Linux) {
        emit_line(out, std::format(".size {}, .-{}", symbol, symbol));
    }

    return out;
}

void Arm64AsmEmitter::emit_prologue(const ir::IrFunction& func, std::string& out) {
    emit_line(out, "stp x29, x30, [sp, #-16]!");
    emit_line(out, "mov x29, sp");

    for (uint8_t r = 19; r <= 27; r += 2) {
        bool r_used     = (alloc_.used_registers_mask & (1U << r)) != 0;
        bool next_used  = (alloc_.used_registers_mask & (1U << (r + 1))) != 0;
        if (r_used || next_used) {
            emit_line(out, std::format("stp x{}, x{}, [sp, #-16]!", r, r + 1));
        }
    }

    if (frame_size_ > 0) {
        emit_line(out, std::format("sub sp, sp, #{}", frame_size_));
    }

    for (size_t i = 0; i < func.parameters.size() && i < 8; ++i) {
        WReg arg_reg{static_cast<uint8_t>(i)};
        emit_store_reg(arg_reg, func.parameters[i].reg, out);
    }
}

void Arm64AsmEmitter::emit_epilogue(std::string& out) {
    if (frame_size_ > 0) {
        emit_line(out, std::format("add sp, sp, #{}", frame_size_));
    }

    for (uint8_t r = 27; r >= 19; r -= 2) {
        bool r_used    = (alloc_.used_registers_mask & (1U << r)) != 0;
        bool next_used = (alloc_.used_registers_mask & (1U << (r + 1))) != 0;
        if (r_used || next_used) {
            emit_line(out, std::format("ldp x{}, x{}, [sp], #16", r, r + 1));
        }
    }

    emit_line(out, "ldp x29, x30, [sp], #16");
    emit_line(out, "ret");
}

namespace {

std::string format_wreg(WReg r) {
    if (r.id == reg::wzr.id) {
        return "wzr";
    }
    return std::format("w{}", r.id);
}

}  // namespace

WReg Arm64AsmEmitter::resolve_src(const ir::IrOperand& op, WReg scratch, std::string& out) {
    if (op.kind == ir::IrOperandKind::Constant) {
        int32_t val = static_cast<int32_t>(op.constant_int);
        if (val >= 0 && val <= 65535) {
            emit_line(out, std::format("mov w{}, #{}", scratch.id, val));
        } else {
            uint32_t bits = static_cast<uint32_t>(val);
            uint16_t lo   = static_cast<uint16_t>(bits & 0xFFFFU);
            uint16_t hi   = static_cast<uint16_t>((bits >> 16) & 0xFFFFU);
            emit_line(out, std::format("movz w{}, #{}", scratch.id, lo));
            if (hi != 0) {
                emit_line(out, std::format("movk w{}, #{}, lsl #16", scratch.id, hi));
            }
        }
        return scratch;
    }

    if (op.kind == ir::IrOperandKind::Variable || op.kind == ir::IrOperandKind::Temporary) {
        if (op.reg < alloc_.locations.size()) {
            const auto& loc = alloc_.locations[op.reg];
            if (loc.kind == jit::StorageKind::Register && loc.index >= 19) {
                return WReg{static_cast<uint8_t>(loc.index)};
            }
            // スピルスロットからのロード
            emit_line(out, std::format("ldr w{}, [sp, #{}]", scratch.id, stack_offset(loc.index)));
            return scratch;
        }
    }

    return scratch;
}

WReg Arm64AsmEmitter::resolve_dst(ir::RegId dst_reg, WReg scratch) const noexcept {
    if (dst_reg < alloc_.locations.size()) {
        const auto& loc = alloc_.locations[dst_reg];
        if (loc.kind == jit::StorageKind::Register && loc.index >= 19) {
            return WReg{static_cast<uint8_t>(loc.index)};
        }
    }
    return scratch;
}

void Arm64AsmEmitter::emit_store_reg(WReg src, ir::RegId dst_reg, std::string& out) {
    if (dst_reg < alloc_.locations.size()) {
        const auto& loc = alloc_.locations[dst_reg];
        std::string src_name = format_wreg(src);
        if (loc.kind == jit::StorageKind::Register && loc.index >= 19) {
            if (loc.index != src.id) {
                emit_line(out, std::format("mov w{}, {}", loc.index, src_name));
            }
        } else {
            // スピルスロットへのストア
            emit_line(out, std::format("str {}, [sp, #{}]", src_name, stack_offset(loc.index)));
        }
    }
}

void Arm64AsmEmitter::emit_instruction(const ir::IrFunction& func, const ir::IrInstruction& inst, size_t inst_idx, std::string& out) {
    (void)func;
    (void)inst_idx;

    switch (inst.op) {
        case ir::IrOpcode::Nop:
            break;

        case ir::IrOpcode::Alloca:
            emit_store_reg(reg::wzr, inst.dest.reg, out);
            break;

        case ir::IrOpcode::Assign: {
            WReg src = resolve_src(inst.src1, reg::w9, out);
            emit_store_reg(src, inst.dest.reg, out);
            break;
        }

        case ir::IrOpcode::Add: {
            WReg s1  = resolve_src(inst.src1, reg::w9, out);
            WReg s2  = resolve_src(inst.src2, reg::w10, out);
            WReg dst = resolve_dst(inst.dest.reg, reg::w8);
            emit_line(out, std::format("add w{}, w{}, w{}", dst.id, s1.id, s2.id));
            emit_store_reg(dst, inst.dest.reg, out);
            break;
        }

        case ir::IrOpcode::Sub: {
            WReg s1  = resolve_src(inst.src1, reg::w9, out);
            WReg s2  = resolve_src(inst.src2, reg::w10, out);
            WReg dst = resolve_dst(inst.dest.reg, reg::w8);
            emit_line(out, std::format("sub w{}, w{}, w{}", dst.id, s1.id, s2.id));
            emit_store_reg(dst, inst.dest.reg, out);
            break;
        }

        case ir::IrOpcode::Mul: {
            WReg s1  = resolve_src(inst.src1, reg::w9, out);
            WReg s2  = resolve_src(inst.src2, reg::w10, out);
            WReg dst = resolve_dst(inst.dest.reg, reg::w8);
            emit_line(out, std::format("mul w{}, w{}, w{}", dst.id, s1.id, s2.id));
            emit_store_reg(dst, inst.dest.reg, out);
            break;
        }

        case ir::IrOpcode::Div: {
            WReg s1  = resolve_src(inst.src1, reg::w9, out);
            WReg s2  = resolve_src(inst.src2, reg::w10, out);
            WReg dst = resolve_dst(inst.dest.reg, reg::w8);
            emit_line(out, std::format("sdiv w{}, w{}, w{}", dst.id, s1.id, s2.id));
            emit_store_reg(dst, inst.dest.reg, out);
            break;
        }

        case ir::IrOpcode::CmpEq: {
            WReg s1  = resolve_src(inst.src1, reg::w9, out);
            WReg s2  = resolve_src(inst.src2, reg::w10, out);
            WReg dst = resolve_dst(inst.dest.reg, reg::w8);
            emit_line(out, std::format("cmp w{}, w{}", s1.id, s2.id));
            emit_line(out, std::format("cset w{}, eq", dst.id));
            emit_store_reg(dst, inst.dest.reg, out);
            break;
        }

        case ir::IrOpcode::CmpNe: {
            WReg s1  = resolve_src(inst.src1, reg::w9, out);
            WReg s2  = resolve_src(inst.src2, reg::w10, out);
            WReg dst = resolve_dst(inst.dest.reg, reg::w8);
            emit_line(out, std::format("cmp w{}, w{}", s1.id, s2.id));
            emit_line(out, std::format("cset w{}, ne", dst.id));
            emit_store_reg(dst, inst.dest.reg, out);
            break;
        }

        case ir::IrOpcode::CmpLt: {
            WReg s1  = resolve_src(inst.src1, reg::w9, out);
            WReg s2  = resolve_src(inst.src2, reg::w10, out);
            WReg dst = resolve_dst(inst.dest.reg, reg::w8);
            emit_line(out, std::format("cmp w{}, w{}", s1.id, s2.id));
            emit_line(out, std::format("cset w{}, lt", dst.id));
            emit_store_reg(dst, inst.dest.reg, out);
            break;
        }

        case ir::IrOpcode::CmpLe: {
            WReg s1  = resolve_src(inst.src1, reg::w9, out);
            WReg s2  = resolve_src(inst.src2, reg::w10, out);
            WReg dst = resolve_dst(inst.dest.reg, reg::w8);
            emit_line(out, std::format("cmp w{}, w{}", s1.id, s2.id));
            emit_line(out, std::format("cset w{}, le", dst.id));
            emit_store_reg(dst, inst.dest.reg, out);
            break;
        }

        case ir::IrOpcode::CmpGt: {
            WReg s1  = resolve_src(inst.src1, reg::w9, out);
            WReg s2  = resolve_src(inst.src2, reg::w10, out);
            WReg dst = resolve_dst(inst.dest.reg, reg::w8);
            emit_line(out, std::format("cmp w{}, w{}", s1.id, s2.id));
            emit_line(out, std::format("cset w{}, gt", dst.id));
            emit_store_reg(dst, inst.dest.reg, out);
            break;
        }

        case ir::IrOpcode::CmpGe: {
            WReg s1  = resolve_src(inst.src1, reg::w9, out);
            WReg s2  = resolve_src(inst.src2, reg::w10, out);
            WReg dst = resolve_dst(inst.dest.reg, reg::w8);
            emit_line(out, std::format("cmp w{}, w{}", s1.id, s2.id));
            emit_line(out, std::format("cset w{}, ge", dst.id));
            emit_store_reg(dst, inst.dest.reg, out);
            break;
        }

        case ir::IrOpcode::Return:
            if (inst.src1.kind != ir::IrOperandKind::None) {
                WReg ret_val = resolve_src(inst.src1, reg::w0, out);
                if (ret_val.id != reg::w0.id) {
                    emit_line(out, std::format("mov w0, w{}", ret_val.id));
                }
            }
            emit_epilogue(out);
            break;

        case ir::IrOpcode::Label:
            emit_label(out, std::format("{}:", format_local_label(inst.label)));
            break;

        case ir::IrOpcode::Jump:
            emit_line(out, std::format("b {}", format_local_label(inst.label)));
            break;

        case ir::IrOpcode::BranchIfFalse: {
            WReg cond = resolve_src(inst.src1, reg::w9, out);
            emit_line(out, std::format("cbz w{}, {}", cond.id, format_local_label(inst.label)));
            break;
        }

        // --- Milestone 3-B: 関数呼び出し (開発者が実装) ---
        case ir::IrOpcode::Call: {
            uint32_t count = (inst.arg_count <= 8) ? inst.arg_count : 8;
            for (uint32_t i = 0; i < count; ++i) {
                WReg arg_reg{static_cast<uint8_t>(i)};
                WReg src = resolve_src(func.call_args[inst.arg_start + i], arg_reg, out);
                if (src.id != arg_reg.id) {
                    emit_line(out, std::format("mov w{}, w{}", arg_reg.id, src.id));
                }
            }

            std::string target_sym = format_symbol(interner_.GetString(inst.call_func_name));
            emit_line(out, std::format("bl {}", target_sym));

            if (inst.dest.kind != ir::IrOperandKind::None) {
                emit_store_reg(reg::w0, inst.dest.reg, out);
            }
            break;
        }

        default:
            break;
    }
}

